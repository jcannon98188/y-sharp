using System;
using System.Buffers;
using System.Collections.Generic;
using System.Linq;
using Xunit;
using YSharp.Tests.Codecs;
using YSharp.TestKit.Traceability;
using YSharp.TestKit.Gating;

namespace YSharp.Tests.Protocols;

internal static class SyncSupport
{
    public static Doc DocWith(ulong client, string? text = null)
    {
        var doc = new Doc(new DocOptions { ClientId = client });
        if (text != null) doc.GetText("t").Insert(0, text);
        return doc;
    }

    public static byte[] Write(Action<ArrayBufferWriter<byte>> body)
    {
        var w = new ArrayBufferWriter<byte>();
        body(w);
        return w.WrittenSpan.ToArray();
    }

    public static byte[] Step1(Doc d) => Write(w => YSync.WriteStep1(w, d));
    public static byte[] Step2(Doc d, byte[]? sv = null) => Write(w => YSync.WriteStep2(w, d, sv ?? ReadOnlySpan<byte>.Empty));
    public static byte[] Update(byte[] u) => Write(w => YSync.WriteUpdate(w, u));

    public sealed record ReadOutcome(YStatus Status, SyncReadResult Result, byte[] Reply, int Consumed, int HandlerCalls);

    public static ReadOutcome Read(Doc doc, byte[] message, object? origin = null)
    {
        ReadOnlySpan<byte> span = message;
        var reply = new ArrayBufferWriter<byte>();
        var calls = 0;
        var status = YSync.TryReadMessage(ref span, reply, doc, origin, out var result, _ => calls++);
        return new ReadOutcome(status, result, reply.WrittenSpan.ToArray(), message.Length - span.Length, calls);
    }

    /// <summary>The varuint length prefix of a message body: returns (type, payload).</summary>
    public static (int Type, byte[] Payload) Split(byte[] message)
    {
        var pos = 0;
        var type = (int)AwBytes.ReadVarUint(message, ref pos);
        var len = (int)AwBytes.ReadVarUint(message, ref pos);
        Assert.Equal(message.Length, pos + len);
        return (type, message.Skip(pos).ToArray());
    }
}

/// <summary>Writers and readers of sync.js (SY-1..12, SY-16..20). Golden bytes are in fixtures/sync, generated by the oracle.</summary>
[Requires(Feature.Sync)]
public sealed class SyncTests
{
    [Fact, Covers("SY-1")]
    public void MessageTypes_AreZeroOneTwo_AndLeadEveryMessage()
    {
        Assert.Equal(new byte[] { 0, 1, 2 }, new[] { (byte)SyncMessageType.Step1, (byte)SyncMessageType.Step2, (byte)SyncMessageType.Update });
        var doc = SyncSupport.DocWith(1, "hi");
        Assert.Equal(0, SyncSupport.Split(SyncSupport.Step1(doc)).Type);
        Assert.Equal(1, SyncSupport.Split(SyncSupport.Step2(doc)).Type);
        Assert.Equal(2, SyncSupport.Split(SyncSupport.Update(new byte[] { 1, 2 })).Type);
    }

    [Fact, Covers("SY-2")]
    public void Payloads_AnyMessage_AreYjsV1Encodings()
    {
        var doc = SyncSupport.DocWith(1, "hello");
        Assert.Equal(Wire.StateVector(doc), SyncSupport.Split(SyncSupport.Step1(doc)).Payload);
        Assert.Equal(doc.EncodeStateAsUpdate(default, UpdateFormat.V1), SyncSupport.Split(SyncSupport.Step2(doc)).Payload);
    }

    [Fact, Covers("SY-3")]
    public void WriteStep1_AnyDoc_IsTypeZeroThenTheLengthPrefixedStateVector()
    {
        var doc = SyncSupport.DocWith(1, "hello");
        var sv = Wire.StateVector(doc);
        Assert.Equal(new byte[] { 0, (byte)sv.Length }.Concat(sv), SyncSupport.Step1(doc));
    }

    [Fact, Covers("SY-4")]
    public void WriteStep2_IsTypeOneThenTheUpdate_FullOrDiffedAgainstAStateVector()
    {
        var doc = SyncSupport.DocWith(1, "hello");
        var other = SyncSupport.DocWith(2, "xy");
        var sv = Wire.StateVector(other);
        var full = doc.EncodeStateAsUpdate();
        Assert.Equal(new byte[] { 1, (byte)full.Length }.Concat(full), SyncSupport.Step2(doc));
        var diff = doc.EncodeStateAsUpdate(sv);
        Assert.Equal(new byte[] { 1, (byte)diff.Length }.Concat(diff), SyncSupport.Step2(doc, sv));
    }

    [Fact, Covers("SY-5")]
    public void WriteUpdate_InvalidBytes_AreNotValidated()
    {
        Assert.Equal(new byte[] { 2, 4, 1, 2, 3, 255 }, SyncSupport.Update(new byte[] { 1, 2, 3, 255 }));
        Assert.Equal(new byte[] { 2, 0 }, SyncSupport.Update(Array.Empty<byte>()));
        var big = SyncSupport.Update(new byte[200]);
        Assert.Equal(new byte[] { 2, 0xc8, 0x01 }, big.Take(3));
    }

    [Fact, Covers("SY-6")]
    public void Writers_AppendToTheGivenWriter_SoMessagesCanBeCombined()
    {
        var doc = SyncSupport.DocWith(1, "hello");
        var w = new ArrayBufferWriter<byte>();
        w.Write(new byte[] { 0xaa });
        YSync.WriteStep1(w, doc);
        YSync.WriteUpdate(w, new byte[] { 9 });
        var bytes = w.WrittenSpan.ToArray();
        Assert.Equal(0xaa, bytes[0]);
        var step1 = SyncSupport.Step1(doc);
        Assert.Equal(step1, bytes.Skip(1).Take(step1.Length));
        Assert.Equal(new byte[] { 2, 1, 9 }, bytes.Skip(1 + step1.Length));
    }

    [Fact, Covers("SY-7", "SY-12")]
    public void ReadStep1_AppendsAStep2Reply_AndDoesNotTouchTheDoc()
    {
        var a = SyncSupport.DocWith(1, "hello");
        var b = SyncSupport.DocWith(2);
        var before = a.EncodeStateAsUpdate();
        var read = SyncSupport.Read(a, SyncSupport.Step1(b));
        Assert.True(read.Status.Ok);
        Assert.Equal(SyncMessageType.Step1, read.Result.Type);
        Assert.True(read.Result.ReplyWritten);
        Assert.Equal(SyncSupport.Step2(a, Wire.StateVector(b)), read.Reply);
        Assert.Equal(before, a.EncodeStateAsUpdate());
    }

    [Fact, Covers("SY-8", "SY-10")]
    [Requires(Feature.Events)]
    public void ReadStep2_AppliesTheUpdate_WithTheGivenTransactionOrigin()
    {
        var a = SyncSupport.DocWith(1, "hello");
        var b = SyncSupport.DocWith(2);
        var origins = new List<object?>();
        b.Update += (_, origin, _, _) => origins.Add(origin);
        var token = new object();
        var read = SyncSupport.Read(b, SyncSupport.Step2(a), token);
        Assert.True(read.Status.Ok);
        Assert.True(read.Result.Apply.Ok);
        Assert.False(read.Result.ReplyWritten);
        Assert.Equal(a.EncodeStateAsUpdate(), b.EncodeStateAsUpdate());
        Assert.Same(token, Assert.Single(origins));
    }

    [Fact, Covers("SY-9")]
    public void Step2AndUpdate_OnReceipt_AreBehaviourallyIdentical()
    {
        var source = SyncSupport.DocWith(1, "hello");
        var payload = source.EncodeStateAsUpdate();
        var viaStep2 = SyncSupport.DocWith(2);
        var viaUpdate = SyncSupport.DocWith(3);
        var r2 = SyncSupport.Read(viaStep2, SyncSupport.Write(w => YSync.WriteStep2(w, source)));
        var ru = SyncSupport.Read(viaUpdate, SyncSupport.Update(payload));
        Assert.Equal(SyncMessageType.Step2, r2.Result.Type);
        Assert.Equal(SyncMessageType.Update, ru.Result.Type);
        Assert.Equal(r2.Status.Ok, ru.Status.Ok);
        Assert.Equal(r2.Reply, ru.Reply);
        Assert.Equal(r2.Consumed, ru.Consumed);
        Assert.Equal(viaStep2.EncodeStateAsUpdate(), viaUpdate.EncodeStateAsUpdate());
    }

    [Fact, Covers("SY-11")]
    public void ReadMessage_DispatchesOnTheType_ReturnsIt_AndConsumesExactlyOneMessage()
    {
        var a = SyncSupport.DocWith(1, "hello");
        var two = SyncSupport.Step2(a).Concat(SyncSupport.Update(Array.Empty<byte>())).ToArray();
        var first = SyncSupport.Read(SyncSupport.DocWith(2), two);
        Assert.Equal(SyncMessageType.Step2, first.Result.Type);
        Assert.Equal(SyncSupport.Step2(a).Length, first.Consumed);
    }

    [Fact, Covers("SY-11", "SY-20")]
    public void UnknownType_IsAnErrorResult_NotAnException()
    {
        var read = SyncSupport.Read(SyncSupport.DocWith(1), new byte[] { 3, 0 });
        Assert.False(read.Status.Ok);
        Assert.Equal(YError.UnknownMessage, read.Status.Error);
    }

    [Fact, Covers("SY-12")]
    public void Reply_Step1Received_IsProducedByStep1Only()
    {
        var a = SyncSupport.DocWith(1, "hello");
        Assert.Empty(SyncSupport.Read(SyncSupport.DocWith(2), SyncSupport.Step2(a)).Reply);
        Assert.Empty(SyncSupport.Read(SyncSupport.DocWith(3), SyncSupport.Update(a.EncodeStateAsUpdate())).Reply);
        Assert.NotEmpty(SyncSupport.Read(SyncSupport.DocWith(4), SyncSupport.Step1(a)).Reply);
    }

    [Fact, Covers("SY-16")]
    public void Step1WithAnEmptyVector_YieldsTheWholeDoc_AndAVectorAheadOfTheDocYieldsAnEmptyUpdate()
    {
        var a = SyncSupport.DocWith(1, "hello");
        var empty = SyncSupport.Read(a, SyncSupport.Write(w => w.Write(new byte[] { 0, 1, 0 })));
        Assert.Equal(SyncSupport.Step2(a), empty.Reply);
        var ahead = SyncSupport.DocWith(1, "hello world");
        var reply = SyncSupport.Read(a, SyncSupport.Step1(ahead)).Reply;
        var fresh = SyncSupport.DocWith(2);
        Assert.True(SyncSupport.Read(fresh, reply).Status.Ok);
        Assert.Equal(new Doc().EncodeStateAsUpdate(), fresh.EncodeStateAsUpdate());
    }

    [Fact, Covers("SY-17")]
    [Requires(Feature.Text)]
    public void AnUpdateWithMissingDependencies_StaysPending_WithoutAnError_AndALaterOneCompletesIt()
    {
        var source = SyncSupport.DocWith(1, "one");
        var first = source.EncodeStateAsUpdate();
        var sv1 = Wire.StateVector(source);
        source.GetText("t").Insert(3, "two");
        var second = source.EncodeStateAsUpdate(sv1);

        var peer = SyncSupport.DocWith(2);
        var read = SyncSupport.Read(peer, SyncSupport.Update(second));
        Assert.True(read.Status.Ok);
        Assert.Equal(0, read.HandlerCalls);
        Assert.Equal("", peer.GetText("t").ToString());
        Assert.True(SyncSupport.Read(peer, SyncSupport.Update(first)).Status.Ok);
        Assert.Equal("onetwo", peer.GetText("t").ToString());
    }

    [Fact, Covers("SY-18")]
    public void Step2_AppliedTwice_IsIdempotent()
    {
        var a = SyncSupport.DocWith(1, "hello");
        var b = SyncSupport.DocWith(2);
        var message = SyncSupport.Step2(a);
        SyncSupport.Read(b, message);
        var once = b.EncodeStateAsUpdate();
        SyncSupport.Read(b, message);
        Assert.Equal(once, b.EncodeStateAsUpdate());
    }

    [Fact, Covers("SY-8", "SY-19")]
    public void CorruptUpdateBytes_GoToTheErrorHandler_NotToTheCaller()
    {
        foreach (var type in new byte[] { 1, 2 })
        {
            var doc = SyncSupport.DocWith(1, "keep");
            var before = doc.EncodeStateAsUpdate();
            var read = SyncSupport.Read(doc, new byte[] { type, 3, 0xff, 0xff, 0xff });
            Assert.True(read.HandlerCalls > 0 || !read.Result.Apply.Ok || !read.Status.Ok);
            Assert.Equal(before, doc.EncodeStateAsUpdate());
        }
    }

    [Fact, Covers("SY-20", "SY-7")]
    public void MissingPayloadBytes_AreAnErrorForStep1_AndAReportedErrorForStep2AndUpdate()
    {
        var step1 = SyncSupport.Read(SyncSupport.DocWith(1), new byte[] { 0 });
        Assert.False(step1.Status.Ok);
        Assert.Equal(0, step1.HandlerCalls);
        foreach (var type in new byte[] { 1, 2 })
        {
            var read = SyncSupport.Read(SyncSupport.DocWith(1), new byte[] { type });
            Assert.True(read.HandlerCalls > 0 || !read.Status.Ok || !read.Result.Apply.Ok);
        }
        var badSv = SyncSupport.Read(SyncSupport.DocWith(1), new byte[] { 0, 2, 0xff, 0xff });
        Assert.False(badSv.Status.Ok);
    }
}
